"use client";

import { useState } from "react";
import { AnalysisResult } from "@/types";
import { ClauseCard } from "./ClauseCard";
import { JURISDICTION_LABELS, CLAUSE_TYPE_LABELS } from "@/types";

interface ResultsViewProps {
  result: AnalysisResult;
  onReset?: () => void;
}

export function ResultsView({ result, onReset }: ResultsViewProps) {
  const [copied, setCopied] = useState(false);
  const { summary, clauses, document_name, jurisdiction, flagged_clauses, total_clauses_found, share_url } = result;

  const highRisk = clauses.filter((c) => c.risk_level === "high");
  const medRisk = clauses.filter((c) => c.risk_level === "medium");
  const lowRisk = clauses.filter((c) => c.risk_level === "low");

  // Sort clauses: high → medium → low
  const sortedClauses = [...highRisk, ...medRisk, ...lowRisk];

  const handleShare = async () => {
    const frontendShareUrl = `${window.location.origin}/report/${result.analysis_id}`;
    if (navigator.share) {
      try {
        await navigator.share({
          title: `ClauseGuard Risk Report: ${document_name}`,
          text: `Check out this AI risk analysis for "${document_name}". Found ${flagged_clauses} risky clauses.`,
          url: frontendShareUrl,
        });
        return;
      } catch (error) {
        if ((error as Error).name !== 'AbortError') {
          console.error('Error sharing:', error);
        }
      }
    }
    navigator.clipboard.writeText(frontendShareUrl);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    let content = `========================================\n`;
    content += `       CLAUSEGUARD RISK REPORT\n`;
    content += `========================================\n\n`;
    content += `Document: ${document_name}\n`;
    content += `Jurisdiction: ${JURISDICTION_LABELS[jurisdiction]}\n`;
    content += `Risk Score: ${result.summary.risk_score}/10 (${result.summary.risk_label.toUpperCase()})\n\n`;
    content += `Summary:\n${result.summary.one_liner}\n\n`;
    
    content += `Top Concerns:\n`;
    result.summary.top_concerns.forEach(c => {
      content += `- ${c}\n`;
    });
    content += `\n========================================\n`;
    content += `          CLAUSE BREAKDOWN\n`;
    content += `========================================\n\n`;

    sortedClauses.forEach((clause, index) => {
      content += `[${index + 1}] ${CLAUSE_TYPE_LABELS[clause.clause_type]} (${clause.risk_level.toUpperCase()} RISK - Score: ${clause.risk_score}/10)\n`;
      content += `Original Text:\n"${clause.original_text}"\n\n`;
      content += `Plain English Meaning:\n${clause.plain_english}\n\n`;
      content += `Why it's Risky:\n${clause.why_risky}\n\n`;
      content += `How to Negotiate:\n${clause.negotiation_suggestion}\n`;
      content += `\n----------------------------------------\n\n`;
    });

    content += `Generated by ClauseGuard (Not Legal Advice)\n`;

    const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `ClauseGuard_Report_${document_name.replace(/[^a-z0-9]/gi, '_').toLowerCase()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="w-full max-w-3xl mx-auto space-y-8 animate-fade-in">
      {/* Header bar */}
      <div className="flex items-center justify-between warm-card px-6 py-5 rounded-2xl">
        <div>
          <h2 className="text-xl font-black text-stone-900 truncate max-w-xs">{document_name}</h2>
          <p className="text-sm font-semibold text-stone-500 mt-1">
            {JURISDICTION_LABELS[jurisdiction]} · {total_clauses_found} clause{total_clauses_found !== 1 ? "s" : ""} detected
          </p>
        </div>
        <div className="flex items-center gap-3">
          {share_url && (
            <button
              id="share-btn"
              onClick={handleShare}
              className={`flex items-center gap-2 px-4 py-2.5 rounded-xl text-sm font-bold transition-all border ${
                copied 
                  ? "bg-emerald-50 border-emerald-200 text-emerald-700" 
                  : "bg-white border-stone-200 text-stone-700 hover:bg-stone-50"
              }`}
            >
              {copied ? (
                <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M5 13l4 4L19 7" />
                </svg>
              ) : (
                <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M8.684 13.342C8.886 12.938 9 12.482 9 12c0-.482-.114-.938-.316-1.342m0 2.684a3 3 0 110-2.684m0 2.684l6.632 3.316m-6.632-6l6.632-3.316m0 0a3 3 0 105.367-2.684 3 3 0 00-5.367 2.684zm0 9.316a3 3 0 105.368 2.684 3 3 0 00-5.368-2.684z" />
                </svg>
              )}
              {copied ? "Copied!" : "Share"}
            </button>
          )}
          <button
            onClick={handleDownload}
            className="flex items-center gap-2 px-4 py-2.5 rounded-xl bg-white border border-stone-200 text-stone-700 hover:bg-stone-50 font-bold text-sm transition-all"
            title="Download Text Report"
          >
            <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4" />
            </svg>
            Download
          </button>
          {onReset && (
            <button
              id="new-analysis-btn"
              onClick={onReset}
              className="flex items-center gap-2 px-4 py-2.5 rounded-xl btn-primary font-bold text-sm"
            >
              + New Analysis
            </button>
          )}
        </div>
      </div>

      {/* Risk score hero card */}
      <div className="warm-card p-8 sm:p-10 rounded-3xl relative overflow-hidden">
        <div className="relative flex flex-col sm:flex-row items-center gap-8">
          {/* Score dial */}
          <div className="flex-shrink-0">
            <div className={`
              w-28 h-28 rounded-3xl flex flex-col items-center justify-center
              border-4 shadow-sm bg-white
              ${summary.risk_score >= 7 ? "border-red-500 text-red-600" :
                summary.risk_score >= 4 ? "border-amber-400 text-amber-600" :
                "border-emerald-500 text-emerald-600"}
            `}>
              <span className="text-4xl font-black">{summary.risk_score}</span>
              <span className="text-sm font-bold opacity-70 mt-1">/ 10</span>
            </div>
          </div>

          {/* Summary text */}
          <div className="flex-1 min-w-0 text-center sm:text-left">
            <div className="flex flex-col sm:flex-row items-center gap-3 mb-4">
              <span className={`text-sm px-3.5 py-1.5 rounded-lg font-black tracking-wider ${
                summary.risk_label === "high" ? "bg-red-600 text-white" :
                summary.risk_label === "medium" ? "bg-amber-500 text-white" :
                "bg-emerald-600 text-white"
              }`}>
                {summary.risk_label.toUpperCase()} RISK
              </span>
              <span className="text-stone-500 text-sm font-bold">{flagged_clauses} flagged clause{flagged_clauses !== 1 ? "s" : ""}</span>
            </div>
            <p className="text-stone-800 font-medium text-lg leading-relaxed">{summary.one_liner}</p>
          </div>
        </div>

        {/* Top 3 concerns */}
        {summary.top_concerns.length > 0 && (
          <div className="mt-8 pt-8 border-t border-stone-200">
            <p className="text-xs text-stone-400 font-bold uppercase tracking-wider mb-5">Top {summary.top_concerns.length} Things to Renegotiate</p>
            <ul className="space-y-4">
              {summary.top_concerns.map((concern, i) => (
                <li key={i} className="flex items-start gap-4 text-base text-stone-700 font-medium leading-relaxed">
                  <span className="w-7 h-7 flex-shrink-0 rounded-full bg-stone-900 text-white flex items-center justify-center text-sm font-black mt-0.5">
                    {i + 1}
                  </span>
                  {concern}
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>

      {/* Risk breakdown stats */}
      <div className="grid grid-cols-3 gap-6">
        {[
          { label: "High Risk", count: highRisk.length, color: "text-red-600", bg: "bg-red-50" },
          { label: "Medium Risk", count: medRisk.length, color: "text-amber-600", bg: "bg-amber-50" },
          { label: "Low Risk", count: lowRisk.length, color: "text-emerald-600", bg: "bg-emerald-50" },
        ].map(({ label, count, color, bg }) => (
          <div key={label} className={`warm-card p-6 text-center ${bg}`}>
            <p className={`text-4xl font-black ${color}`}>{count}</p>
            <p className="text-xs font-bold text-stone-500 uppercase tracking-wider mt-3">{label}</p>
          </div>
        ))}
      </div>

      {/* Clauses list */}
      <div className="space-y-5 pt-6">
        <h3 className="text-sm font-bold text-stone-400 uppercase tracking-wider border-b border-stone-200 pb-3 mb-6">Clause-by-Clause Analysis</h3>
        {sortedClauses.map((clause, i) => (
          <ClauseCard key={`${clause.clause_type}-${i}`} clause={clause} index={i} />
        ))}
      </div>

      {/* Footer disclaimer */}
      <p className="text-center text-xs font-bold text-stone-400 uppercase tracking-wider pb-6">
        Not Legal Advice · Always Consult a Lawyer
      </p>
    </div>
  );
}
